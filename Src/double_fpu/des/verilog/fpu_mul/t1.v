module fpu_mul (
    input clk,
    input rst,
    input enable,
    input [63:0] opa,
    input [63:0] opb,
    output reg sign,
    output [55:0] product_7,
    output reg [11:0] exponent_5
);

reg [5:0]   product_shift;
reg [5:0]   product_shift_2;
reg [51:0]  mantissa_a;
reg [51:0]  mantissa_b;
reg [10:0]  exponent_a;
reg [10:0]  exponent_b;
reg         a_is_norm;
reg         b_is_norm;
reg         a_is_zero;
reg         b_is_zero;
reg         in_zero;
reg [11:0]  exponent_terms;
reg         exponent_gt_expoffset;
reg [11:0]  exponent_under;
reg [11:0]  exponent_1;
reg [11:0]  exponent_2;
reg         exponent_gt_prodshift;
reg [11:0]  exponent_3;
reg [11:0]  exponent_4;
reg         exponent_et_zero;
reg [52:0]  mul_a;
reg [52:0]  mul_b;
reg [40:0]  product_a;
reg [40:0]  product_b;
reg [40:0]  product_c;
reg [25:0]  product_d;
reg [33:0]  product_e;
reg [33:0]  product_f;
reg [35:0]  product_g;
reg [28:0]  product_h;
reg [28:0]  product_i;
reg [30:0]  product_j;
reg [41:0]  sum_0;
reg [35:0]  sum_1;
reg [41:0]  sum_2;
reg [35:0]  sum_3;
reg [36:0]  sum_4;
