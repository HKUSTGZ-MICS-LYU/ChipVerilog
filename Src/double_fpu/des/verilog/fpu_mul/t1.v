reg [30:0]  sum_8;
reg [105:0] product;
reg [105:0] product_1;
reg [105:0] product_2;
reg [105:0] product_3;
reg [105:0] product_4;
reg [105:0] product_5;
reg [105:0] product_6;
reg         product_lsb;

wire [55:0] product_7 = {1'b0, product_6[105:52], product_lsb};

always @(posedge clk or posedge rst) begin
    if (rst) begin
        sign               <= 0;
        mantissa_a         <= 0;
        mantissa_b         <= 0;
        exponent_a         <= 0;
        exponent_b         <= 0;
        a_is_norm          <= 0;
        b_is_norm          <= 0;
        a_is_zero          <= 0;
        b_is_zero          <= 0;
        in_zero            <= 0;
        exponent_terms     <= 0;
        exponent_gt_expoffset <= 0;
        exponent_under     <= 0;
        exponent_1         <= 0;
        exponent_2         <= 0;
        exponent_gt_prodshift <= 0;
        exponent_3         <= 0;
        exponent_4         <= 0;
        exponent_et_zero   <= 0;
        exponent_5         <= 0;
        mul_a              <= 0;
        mul_b              <= 0;
        product_a          <= 0;
        product_b          <= 0;
        product_c          <= 0;
        product_d          <= 0;
        product_e          <= 0;
        product_f          <= 0;
        product_g          <= 0;
        product_h          <= 0;
        product_i          <= 0;
        product_j          <= 0;
        sum_0              <= 0;
        sum_1              <= 0;
        sum_2              <= 0;
        sum_3              <= 0;
        sum_4              <= 0;
        sum_5              <= 0;
        sum_6              <= 0;
        sum_7              <= 0;
        sum_8              <= 0;
        product            <= 0;
        product_1          <= 0;
        product_2          <= 0;
        product_3          <= 0;
        product_4          <= 0;
        product_5          <= 0;
        product_6          <= 0;
        product_lsb        <= 0;
        product_shift_2    <= 0;
    end
    else if (enable) begin
        // Stage 1: field extraction
        sign       <= opa[63] ^ opb[63];
        mantissa_a <= opa[51:0];
        mantissa_b <= opb[51:0];
        exponent_a <= opa[62:52];
        exponent_b <= opb[62:52];
        a_is_norm  <= |opa[62:52];
        b_is_norm  <= |opb[62:52];
        a_is_zero  <= !(|opa[62:0]);
        b_is_zero  <= !(|opb[62:0]);

        // Stage 2: form significands and partial products
        in_zero <= a_is_zero | b_is_zero;
        mul_a   <= {a_is_norm, mantissa_a};
        mul_b   <= {b_is_norm, mantissa_b};

        // Exponent path
        exponent_terms <= exponent_a + exponent_b + !a_is_norm + !b_is_norm;
        exponent_gt_expoffset <= exponent_terms > 1021;
        exponent_under <= 1022 - exponent_terms;
        exponent_1 <= exponent_gt_expoffset ? (exponent_terms - 1022) : 0;

        // Partial products: 53-bit mul_a x 53-bit mul_b decomposed
        // mul_a[52:0] = {mul_a[52:29], mul_a[28:12], mul_a[11:0]}  (24,17,12 bits)
        // mul_b[52:0] = {mul_b[52:34], mul_b[33:17], mul_b[16:0]}  (19,17,17 bits)
        product_a <= mul_a[52:29] * mul_b[16:0];   // 24x17
        product_b <= mul_a[52:29] * mul_b[33:17];  // 24x17
        product_c <= mul_a[52:29] * mul_b[52:34];  // 24x19 -> use [1:0] as 2-bit slice
        product_d <= mul_a[52:29] * mul_b[35:34];  // 24x2
        product_e <= mul_a[28:12] * mul_b[16:0];   // 17x17
        product_f <= mul_a[28:12] * mul_b[33:17];  // 17x17
        product_g <= mul_a[28:12] * mul_b[52:34];  // 17x19
        product_h <= mul_a[11:0]  * mul_b[16:0];   // 12x17 -> [28:0]
        product_i <= mul_a[11:0]  * mul_b[33:17];  // 12x17
        product_j <= mul_a[11:0]  * mul_b[52:34];  // 12x19

        // Stage 3: partial sum tree level 1
        sum_0 <= product_a + (product_e << 24);
        sum_1 <= product_b + (product_f << 0);
        sum_2 <= (product_c << 17) + (product_d << 17);
        sum_3 <= product_g + (product_h >> 12);
        sum_4 <= {product_i, 12'b0} + {product_j, 12'b0};
        sum_5 <= product_h[28:1];
        sum_6 <= product_i[28:0] >> 0;
        sum_7 <= sum_0[36:0] + sum_1;
        sum_8 <= sum_3[30:0] + sum_5;

        // Stage 4: assemble 106-bit product
        product <= {sum_2[35:0], sum_7[35:0], sum_8[29:0], 6'b0}
                 + {10'b0, sum_4[35:0], sum_6[29:0], 10'b0};

        // Exponent stage 2
        exponent_2 <= exponent_1;
        product_shift_2 <= product_shift;

        // Stage 5-10: pipeline product through to product_6
        product_1 <= product;
        exponent_gt_prodshift <= exponent_2 > product_shift_2;
        exponent_3 <= exponent_gt_prodshift ?
                      (exponent_2 - product_shift_2) : 0;

        product_2 <= product_1;
        exponent_4 <= exponent_3;

        product_3 <= exponent_gt_prodshift ?
                     (product_2 << product_shift_2) :
                     (product_2 << exponent_2);

        product_4 <= product_3;
        exponent_et_zero <= (exponent_4 == 0);

        product_5 <= exponent_et_zero ? (product_4 >> 1) : product_4;

        product_6   <= exponent_gt_expoffset ? product_5 :
                       (product_5 >> exponent_under);
        product_lsb <= |product_6[51:0];

        exponent_5 <= in_zero ? 0 : exponent_4;
    end
end

