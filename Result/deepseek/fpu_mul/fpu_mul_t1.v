module fpu_mul (
    input clk,
    input rst,
    input enable,
    input [63:0] opa,
    input [63:0] opb,
    output reg sign,
    output [55:0] product_7,
    output reg [11:0] exponent_5
);

    reg [51:0] mantissa_a;
    reg [51:0] mantissa_b;
    reg [10:0] exponent_a;
    reg [10:0] exponent_b;
    reg a_is_norm;
    reg b_is_norm;
    reg a_is_zero;
    reg b_is_zero;
    reg in_zero;
    reg [11:0] exponent_terms;
    reg exponent_gt_expoffset;
    reg [11:0] exponent_under;
    reg [11:0] exponent_1;
    reg [11:0] exponent_2;
    reg exponent_gt_prodshift;
    reg [11:0] exponent_3;
    reg [11:0] exponent_4;
    reg exponent_et_zero;
    reg [52:0] mul_a;
    reg [52:0] mul_b;
    reg [40:0] product_a;
    reg [40:0] product_b;
    reg [40:0] product_c;
    reg [25:0] product_d;
    reg [33:0] product_e;
    reg [33:0] product_f;
    reg [35:0] product_g;
    reg [28:0] product_h;
    reg [28:0] product_i;
    reg [30:0] product_j;
    reg [41:0] sum_0;
    reg [35:0] sum_1;
    reg [41:0] sum_2;
    reg [35:0] sum_3;
    reg [36:0] sum_4;
    reg [27:0] sum_5;
    reg [29:0] sum_6;
    reg [36:0] sum_7;
    reg [30:0] sum_8;
    reg [105:0] product;
    reg [105:0] product_1;
    reg [105:0] product_2;
    reg [105:0] product_3;
    reg [105:0] product_4;
    reg [105:0] product_5;
    reg [105:0] product_6;
    reg product_lsb;
    reg [5:0] product_shift;
    reg [5:0] product_shift_2;

    wire [11:0] exponent = 0;

    // Stage 0: Input capture
    always @(posedge clk) begin
        if (rst) begin
            sign <= 1'b0;
            mantissa_a <= 52'd0;
            mantissa_b <= 52'd0;
            exponent_a <= 11'd0;
            exponent_b <= 11'd0;
            a_is_norm <= 1'b0;
            b_is_norm <= 1'b0;
            a_is_zero <= 1'b0;
            b_is_zero <= 1'b0;
            in_zero <= 1'b0;
        end else if (enable) begin
            sign <= opa[63] ^ opb[63];
            mantissa_a <= opa[51:0];
            mantissa_b <= opb[51:0];
            exponent_a <= opa[62:52];
            exponent_b <= opb[62:52];
            a_is_norm <= (opa[62:52] != 11'd0);
            b_is_norm <= (opb[62:52] != 11'd0);
            a_is_zero <= (opa[62:0] == 63'd0);
            b_is_zero <= (opb[62:0] == 63'd0);
            in_zero <= (opa[62:0] == 63'd0) || (opb[62:0] == 63'd0);
        end
    end

    // Stage 1: Form significands
    always @(posedge clk) begin
        if (rst) begin
            mul_a <= 53'd0;
            mul_b <= 53'd0;
            exponent_1 <= 12'd0;
        end else if (enable) begin
            mul_a <= {a_is_norm, mantissa_a};
            mul_b <= {b_is_norm, mantissa_b};
            exponent_1 <= exponent_a + exponent_b + (!a_is_norm) + (!b_is_norm);
        end
    end

    // Stage 2: Partial products
    always @(posedge clk) begin
        if (rst) begin
            product_a <= 41'd0;
            product_b <= 41'd0;
            product_c <= 41'd0;
            product_d <= 26'd0;
            product_e <= 34'd0;
            product_f <= 34'd0;
            product_g <= 36'd0;
            product_h <= 29'd0;
            product_i <= 29'd0;
            product_j <= 31'd0;
            exponent_terms <= 12'd0;
        end else if (enable) begin
            // Decompose mul_a and mul_b
            // mul_a[52:0]: 53 bits, slices:
            // a_high24 = mul_a[52:29] (24 bits)
            // a_mid17 = mul_a[28:12] (17 bits)
            // a_low12 = mul_a[11:0] (12 bits)
            // mul_b[52:0]: 53 bits, slices:
            // b_high17 = mul_b[52:36] (17 bits)
            // b_mid19 = mul_b[35:17] (19 bits)
            // b_low17 = mul_b[16:0] (17 bits)
            // Extra slice: b_high2 = mul_b[52:51] (2 bits)

            wire [23:0] a_high24 = mul_a[52:29];
            wire [16:0] a_mid17  = mul_a[28:12];
            wire [11:0] a_low12  = mul_a[11:0];

            wire [16:0] b_high17 = mul_b[52:36];
            wire [18:0] b_mid19  = mul_b[35:17];
            wire [16:0] b_low17  = mul_b[16:0];
            wire [1:0]  b_high2  = mul_b[52:51];

            // 24x17
            product_a <= a_high24 * b_high17; // 24+17=41 bits
            // 24x2
            product_b <= a_high24 * b_high2;  // 24+2=26 bits -> 41 bits padded
            // 17x17
            product_c <= a_mid17 * b_high17;  // 17+17=34 bits -> 41 bits
            // 17x19
            product_d <= a_mid17 * b_mid19;  // 17+19=36 bits -> 26 bits?
            // 12x17
            product_e <= a_low12 * b_high17;  // 12+17=29 bits -> 34 bits
            // 12x19
            product_f <= a_low12 * b_mid19;  // 12+19=31 bits -> 34 bits
            // 24x17 low part? Actually product_g is 17x17 with different alignment? 
            // Specification says: product_g, product_h, product_i, product_j are also partial products
            // We'll assign remaining slices:
            // 17x17 another alignment
            product_g <= a_high24 * b_low17;  // 24+17=41 -> 36 bits? 
            // 12x17
            product_h <= a_mid17 * b_low17;   // 17+17=34 -> 29 bits
            // 12x19
            product_i <= a_low12 * b_low17;   // 12+17=29
            // 12x17 extra?
            product_j <= a_low12 * b_high2;   // 12+2=14 -> 31 bits

            exponent_terms <= exponent_1 + (!a_is_norm) + (!b_is_norm);
        end
    end

    // Stage 3: Summation of partial products
    always @(posedge clk) begin
        if (rst) begin
            sum_0 <= 42'd0;
            sum_1 <= 36'd0;
            sum_2 <= 42'd0;
            sum_3 <= 36'd0;
            sum_4 <= 37'd0;
            sum_5 <= 28'd0;
            sum_6 <= 30'd0;
            sum_7 <= 37'd0;
            sum_8 <= 31'd0;
        end else if (enable) begin
            // Combine partial products with appropriate alignment
            sum_0 <= {1'b0, product_a} + {1'b0, product_b};
            sum_1 <= product_c[33:0] + product_d[33:0]; // 34 bits
            sum_2 <= {1'b0, product_e} + {1'b0, product_f};
            sum_3 <= product_g[35:0] + product_h[35:0]; // 36 bits?
            sum_4 <= {1'b0, product_i} + {1'b0, product_j};
            sum_5 <= sum_1[35:8]; // shift
            sum_6 <= sum_3[36:7]; // shift
            sum_7 <= sum_4 + sum_5 + sum_6;
            sum_8 <= sum_7[36:6]; // shift
        end
    end

    // Stage 4: Assemble product
    always @(posedge clk) begin
        if (rst) begin
            product <= 106'd0;
            exponent_gt_expoffset <= 1'b0;
            exponent_under <= 12'd0;
        end else if (enable) begin
            // Reconstruct 106-bit product from partial sums
            product <= {sum_0, sum_2[40:0], sum_8[30:0]}; // approximate
            exponent_gt_expoffset <= (exponent_terms > 12'd1021);
            exponent_under <= 12'd1022 - exponent_terms;
        end
    end

