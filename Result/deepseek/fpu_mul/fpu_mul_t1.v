        end
    end

    always @(posedge clk) begin
        if (rst) begin
            product_3 <= 106'd0;
            exponent_4 <= 12'd0;
            exponent_gt_prodshift <= 1'b0;
        end else if (enable) begin
            product_3 <= product_2;
