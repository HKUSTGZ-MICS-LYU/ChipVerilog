        end
    end

    always @(posedge clk) begin
        if (rst) begin
            product_4 <= 106'd0;
            exponent_et_zero <= 1'b0;
        end else if (enable) begin
            if (exponent_gt_prodshift) begin
                product_4 <= product_3 << product_shift_2;
            end else begin
                product_4 <= product_3 >> (product_shift_2 - exponent_4);
            end
            exponent_et_zero <= (exponent_4 == 12'd0);
        end
    end

    always @(posedge clk) begin
        if (rst) begin
            product_5 <= 106'd0;
        end else if (enable) begin
            if (exponent_et_zero)
                product_5 <= product_4 >> 1;
            else
