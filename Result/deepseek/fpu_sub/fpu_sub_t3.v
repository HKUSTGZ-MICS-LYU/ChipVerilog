            default: diff_shift = 6'd55; // all zero
        endcase
    end

    // Normalization combinational
    wire diffshift_gt_exponent = diff_shift_2 > exponent_large;
    wire diffshift_et_55 = diff_shift_2 == 6'd55;
    wire [10:0] exponent_tmp = diffshift_gt_exponent ? 11'd0 : (exponent_large - diff_shift_2);
    wire [54:0] diff_1_tmp = diffshift_gt_exponent ? (diff << exponent_large) : (diff << diff_shift_2);
    wire in_norm_out_denorm = (exponent_large != 11'd0) & (exponent_tmp == 11'd0);
    wire [54:0] diff_1_adjusted = in_norm_out_denorm ? (diff_1_tmp >> 1) : diff_1_tmp;

    // Clocked pipeline
    always @(posedge clk) begin
        if (rst) begin
            exponent_a <= 0;
            exponent_b <= 0;
            mantissa_a <= 0;
            mantissa_b <= 0;
            sign_a <= 0;
            sign_b <= 0;
            a_gtet_b <= 0;
            exponent_large <= 0;
            exponent_small <= 0;
            mantissa_large <= 0;
            mantissa_small <= 0;
            small_is_nonzero <= 0;
            exponent_diff <= 0;
            large_norm_small_denorm <= 0;
            sign_pipe <= 0;
            subtra_shift_3 <= 0;
            diff <= 0;
            diff_shift_2 <= 0;
            diff_2 <= 0;
            exponent_2 <= 0;
            sign <= 0;
        end else if (enable) begin
            // Stage 0: input registers
            exponent_a <= opa[62:52];
            exponent_b <= opb[62:52];
            mantissa_a <= opa[51:0];
            mantissa_b <= opb[51:0];
            sign_a <= opa[63];
            sign_b <= opb[63];

            // Stage 1: compare
            a_gtet_b <= expa_gt_expb || (expa_et_expb && mana_gtet_manb);

            // Stage 2: operand selection
            exponent_large <= a_gtet_b ? exponent_a : exponent_b;
            exponent_small <= a_gtet_b ? exponent_b : exponent_a;
            mantissa_large <= a_gtet_b ? mantissa_a : mantissa_b;
            mantissa_small <= a_gtet_b ? mantissa_b : mantissa_a;
            small_is_nonzero <= a_gtet_b ? (|mantissa_b) : (|mantissa_a);
            large_norm_small_denorm <= (a_gtet_b ? (exponent_a != 0) : (exponent_b != 0)) & (a_gtet_b ? (exponent_b == 0) : (exponent_a == 0));
            exponent_diff <= (a_gtet_b ? exponent_a : exponent_b) - (a_gtet_b ? exponent_b : exponent_a) - (large_norm_small_denorm ? 1'b1 : 1'b0);
            sign_pipe <= a_gtet_b ? sign_a : (!sign_b ^ (fpu_op == 3'b000));

            // Stage 3: alignment
            subtra_shift_3 <= subtra_fraction_enable ? subtra_shift_2_const : subtra_shift;

            // Stage 4: subtraction
            diff <= significand_large - subtra_shift_3;

            // Stage 5: leading-zero count
            diff_shift_2 <= diff_shift;

            // Stage 6: output registers
            diff_2 <= {1'b0, diff_1_adjusted};
            exponent_2 <= diffshift_et_55 ? 11'd0 : exponent_tmp;
            sign <= sign_pipe;
        end
    end

endmodule
