module fpu_sub (
    input clk,
    input rst,
    input enable,
    input [63:0] opa,
    input [63:0] opb,
    input [2:0] fpu_op,
    output reg sign,
    output reg [55:0] diff_2,
    output reg [10:0] exponent_2
);

    // Stage 0: input registers
    reg [10:0] exponent_a, exponent_b;
    reg [51:0] mantissa_a, mantissa_b;
    reg sign_a, sign_b;

    // Stage 1: comparison result
    reg a_gtet_b;

    // Stage 2: selected operands and related
    reg [10:0] exponent_large, exponent_small;
    reg [51:0] mantissa_large, mantissa_small;
    reg small_is_nonzero;
    reg [10:0] exponent_diff;
    reg large_norm_small_denorm;
    reg sign_pipe; // sign to be output

    // Stage 3: aligned subtrahend
    reg [54:0] subtra_shift_3;

    // Stage 4: raw subtraction result
    reg [54:0] diff;

    // Stage 5: leading-zero count
    reg [5:0] diff_shift_2;

    // Combinational signals
    wire expa_gt_expb = exponent_a > exponent_b;
    wire expa_et_expb = exponent_a == exponent_b;
    wire mana_gtet_manb = mantissa_a >= mantissa_b;

    wire large_is_norm = exponent_large != 0;
    wire small_is_norm = exponent_small != 0;

    wire [54:0] significand_large = { large_is_norm ? 1'b1 : 1'b0, mantissa_large, 2'b00 };
    wire [54:0] significand_small = { small_is_norm ? 1'b1 : 1'b0, mantissa_small, 2'b00 };

    wire [54:0] subtra_shift = significand_small >> exponent_diff;
    wire subtra_shift_nonzero = |subtra_shift;
    wire subtra_fraction_enable = small_is_nonzero & !subtra_shift_nonzero;
    wire [54:0] subtra_shift_2_const = {54'b0, 1'b1};

    // Leading-zero encoder
    reg [5:0] diff_shift;
