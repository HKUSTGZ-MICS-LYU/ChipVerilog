        casex (diff)
            55'b1??????????????????????????????????????????????????????: diff_shift = 6'd0;
            55'b01?????????????????????????????????????????????????????: diff_shift = 6'd1;
            55'b001????????????????????????????????????????????????????: diff_shift = 6'd2;
            55'b0001???????????????????????????????????????????????????: diff_shift = 6'd3;
            55'b00001??????????????????????????????????????????????????: diff_shift = 6'd4;
            55'b000001?????????????????????????????????????????????????: diff_shift = 6'd5;
            55'b0000001????????????????????????????????????????????????: diff_shift = 6'd6;
            55'b00000001???????????????????????????????????????????????: diff_shift = 6'd7;
            55'b000000001??????????????????????????????????????????????: diff_shift = 6'd8;
