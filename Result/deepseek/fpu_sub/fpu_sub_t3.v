            55'b00000000001????????????????????????????????????????????: diff_shift = 6'd10;
            55'b000000000001???????????????????????????????????????????: diff_shift = 6'd11;
            55'b0000000000001??????????????????????????????????????????: diff_shift = 6'd12;
            55'b00000000000001?????????????????????????????????????????: diff_shift = 6'd13;
            55'b000000000000001????????????????????????????????????????: diff_shift = 6'd14;
