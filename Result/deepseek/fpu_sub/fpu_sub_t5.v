wire mana_gtet_manb;
wire a_gtet_b_w;
wire small_is_denorm;
wire large_is_denorm;
wire large_norm_small_denorm;
wire [10:0] exponent_diff_w;
wire [54:0] minuend, subtrahend;
wire [54:0] subtra_shift;
wire subtra_shift_nonzero;
wire subtra_fraction_enable;
wire [54:0] subtra_shift_2;
wire [5:0] diff_shift;
wire diffshift_gt_exponent;
wire diffshift_et_55;
wire in_norm_out_denorm;

// Continuous assignments for combinational signals
assign expa_gt_expb = (exponent_a > exponent_b);
assign expa_et_expb = (exponent_a == exponent_b);
assign mana_gtet_manb = (mantissa_a >= mantissa_b);
assign a_gtet_b_w = expa_gt_expb ? 1'b1 : (expa_et_expb ? mana_gtet_manb : 1'b0);

assign small_is_denorm = (exponent_small == 0);
assign large_is_denorm = (exponent_large == 0);
assign large_norm_small_denorm = (exponent_large != 0) && (exponent_small == 0);
assign exponent_diff_w = exponent_large - exponent_small - large_norm_small_denorm;

assign minuend = {large_is_denorm ? 1'b0 : 1'b1, mantissa_large, 2'b00};
assign subtrahend = {small_is_denorm ? 1'b0 : 1'b1, mantissa_small, 2'b00};
assign subtra_shift = subtrahend >> exponent_diff;
assign subtra_shift_nonzero = |subtra_shift;
assign subtra_fraction_enable = small_nonzero & !subtra_shift_nonzero;
assign subtra_shift_2 = {54'b0, 1'b1};

assign diffshift_gt_exponent = (diff_shift_2 > exponent_large);
assign diffshift_et_55 = (diff_shift_2 == 6'd55);
assign in_norm_out_denorm = (exponent_large > 0) & (exponent == 0);

