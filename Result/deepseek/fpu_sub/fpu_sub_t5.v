reg a_gtet_b;
reg [10:0] exponent_large, exponent_small;
reg [51:0] mantissa_large, mantissa_small;
reg small_nonzero;
reg [10:0] exponent_diff;
reg [54:0] subtra_shift_3;
reg [54:0] diff;
reg [5:0] diff_shift_2;
reg [54:0] diff_1;
reg [10:0] exponent;
reg diffshift_et_55_reg; // registered version of diffshift_et_55 for output stage

// Wires for combinational logic
wire expa_gt_expb;
