// Main clocked pipeline
always @(posedge clk) begin
    if (rst) begin
        exponent_a <= 0;
        exponent_b <= 0;
        mantissa_a <= 0;
        mantissa_b <= 0;
        a_gtet_b <= 0;
        sign <= 0;
        exponent_large <= 0;
        exponent_small <= 0;
        mantissa_large <= 0;
        mantissa_small <= 0;
        small_nonzero <= 0;
        exponent_diff <= 0;
        subtra_shift_3 <= 0;
        diff <= 0;
        diff_shift_2 <= 0;
        diff_1 <= 0;
        exponent <= 0;
        diffshift_et_55_reg <= 0;
        diff_2 <= 0;
        exponent_2 <= 0;
    end else begin
        if (enable) begin
            // Stage 1: register operand fields (directly from inputs)
            exponent_a <= opa[62:52];
            exponent_b <= opb[62:52];
            mantissa_a <= opa[51:0];
            mantissa_b <= opb[51:0];

            // Stage 2: compare magnitudes and select sign (uses above registered fields next cycle)
            // Note: combinational a_gtet_b_w is computed from current (old) exponent_a etc.
            a_gtet_b <= a_gtet_b_w;
            sign <= a_gtet_b_w ? opa[63] : (!opb[63] ^ (fpu_op == 3'b000));

            // Stage 3: select large/small operands (uses registered a_gtet_b from previous cycle)
            if (a_gtet_b) begin
                exponent_large <= exponent_a;
                exponent_small <= exponent_b;
                mantissa_large <= mantissa_a;
                mantissa_small <= mantissa_b;
            end else begin
                exponent_large <= exponent_b;
                exponent_small <= exponent_a;
                mantissa_large <= mantissa_b;
                mantissa_small <= mantissa_a;
            end
            small_nonzero <= (mantissa_small != 0) || (exponent_small != 0);

            // Stage 4: compute exponent difference (uses registered exponent_large etc.)
            exponent_diff <= exponent_diff_w;

            // Stage 5: alignment and subtrahend adjustment (uses registered exponent_diff from previous)
            subtra_shift_3 <= subtra_fraction_enable ? subtra_shift_2 : subtra_shift;

            // Stage 6: compute difference
            diff <= minuend - subtra_shift_3;

            // Stage 7: leading zero count and normalization inputs
            diff_shift_2 <= diff_shift;

            // Stage 8: normalization
            if (diffshift_gt_exponent) begin
                diff_1 <= diff << exponent_large;
                exponent <= 0;
            end else begin
                diff_1 <= diff << diff_shift_2;
                exponent <= exponent_large - diff_shift_2;
            end
            diffshift_et_55_reg <= diffshift_et_55;

            // Stage 9: final output registers
            exponent_2 <= diffshift_et_55_reg ? 11'd0 : exponent;
            if (in_norm_out_denorm)
                diff_2 <= {1'b0, diff_1 >> 1};
            else
                diff_2 <= {1'b0, diff_1};
        end
    end
end

