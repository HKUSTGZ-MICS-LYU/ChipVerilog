            sign <= 1'b0;
            diff_2 <= 56'b0;
            exponent_2 <= 11'b0;
        end else if (enable) begin
            // Stage 1: Register operand fields
            exponent_a <= opa[62:52];
            exponent_b <= opb[62:52];
            mantissa_a <= opa[51:0];
            mantissa_b <= opb[51:0];

            // Stage 2: Compare magnitudes
            expa_gt_expb <= (exponent_a > exponent_b);
            expa_et_expb <= (exponent_a == exponent_b);
            mana_gtet_manb <= (mantissa_a >= mantissa_b);
            a_gtet_b <= expa_gt_expb || (expa_et_expb && mana_gtet_manb);

            // Stage 3: Select large/small operands and sign
            if (a_gtet_b) begin
                exponent_large <= exponent_a;
                exponent_small <= exponent_b;
                mantissa_large <= mantissa_a;
                mantissa_small <= mantissa_b;
                sign <= opa[63];
            end else begin
                exponent_large <= exponent_b;
                exponent_small <= exponent_a;
                mantissa_large <= mantissa_b;
                mantissa_small <= mantissa_a;
                sign <= (!opb[63]) ^ (fpu_op == 3'b000);
            end

            // Stage 4: Denorm detection and exponent difference
            small_is_denorm <= (exponent_small == 11'b0);
            large_is_denorm <= (exponent_large == 11'b0);
            large_norm_small_denorm <= (!large_is_denorm) && small_is_denorm;
            exponent_diff <= exponent_large - exponent_small - large_norm_small_denorm;

            // Stage 5: Build extended significands
            minuend <= { (!large_is_denorm), mantissa_large, 2'b00 };
            subtrahend <= { (!small_is_denorm), mantissa_small, 2'b00 };
            small_is_nonzero <= (mantissa_small != 52'b0) || !small_is_denorm;

            // Stage 6: Align subtrahend
            subtra_shift <= subtrahend >> exponent_diff;

            // Stage 7: Sticky preservation
            subtra_fraction_enable <= small_is_nonzero && !subtra_shift_nonzero;
            subtra_shift_3 <= subtra_fraction_enable ? subtra_shift_2 : subtra_shift;

            // Stage 8: Subtract significands
            diff <= minuend - subtra_shift_3;

            // Stage 9: Leading-zero count
            diff_shift <= diff_shift_comb;

            // Stage 10: Register shift count
            diff_shift_2 <= diff_shift;
            diffshift_gt_exponent <= (diff_shift > exponent_large);
            diffshift_et_55 <= (diff_shift == 6'd55);

            // Stage 11: Normalize
            if (diffshift_gt_exponent) begin
                diff_1 <= diff << exponent_large;
                exponent <= 11'b0;
            end else begin
                diff_1 <= diff << diff_shift_2;
                exponent <= exponent_large - diff_shift_2;
            end

            // Stage 12: Final output
            in_norm_out_denorm <= (exponent_large > 11'b0) && (exponent == 11'b0);
            exponent_2 <= diffshift_et_55 ? 11'b0 : exponent;
            diff_2 <= {1'b0, in_norm_out_denorm ? (diff_1 >> 1) : diff_1};
        end
    end

endmodule
