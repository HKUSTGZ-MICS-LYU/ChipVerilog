    // Internal registers
    reg [10:0] exponent_a, exponent_b;
    reg [51:0] mantissa_a, mantissa_b;
    reg expa_gt_expb, expa_et_expb;
    reg mana_gtet_manb;
    reg a_gtet_b;
    reg [10:0] exponent_large, exponent_small;
